/**
 * React hook that builds the collection's effective MUI theme.
 *
 * @module hooks/useCollectionTheme
 * @remarks
 * Subscribes to the shared user-theme ioBroker state
 * (`vis-2-widgets-collection.0.theme`), parses/validates it, and merges it onto
 * the host theme (plus optional caller overrides) via `createTheme`.
 *
 * Centralizes the state-reading + `Connection.unsubscribeState` handling so
 * the runtime {@link module:components/CollectionProvider.CollectionProvider} and
 * editor surfaces (which live outside the provider subtree) share one source of
 * truth for the user-configured theme.
 */

import { useEffect, useMemo, useRef, useState } from 'react';
import { deepmerge } from '@mui/utils';
import { THEME_STATE_ID } from '../lib/constants';
import { createThemeCached } from '../lib/theme/createThemeCache';
import { clearDraftTheme, getDraftThemeString } from '../lib/theme/draftThemeStore';
import { withDerivedSecondary, withPrimaryAsText } from '../lib/theme/derivePalette';
import { bundledFamiliesOf, ensureBundledFontFaces } from '../lib/theme/fontCatalogue';
import { injectGoogleFontFaces } from '../lib/theme/googleFonts';
import { validateThemeOptions } from '../lib/theme/validateTheme';
import { buildCornerRadiusCss, getNestedValue } from '../lib/theme/themeUtils';
import useDraftTheme from './useDraftTheme';

import type { Connection } from '@iobroker/adapter-react-v5';
import type { Theme, ThemeOptions } from '@mui/material/styles';
import type { CornerRadii } from '../lib/theme/themeTypes';

/** Standard MUI typography variant keys that `createTypography` regenerates. */
const TYPOGRAPHY_VARIANT_KEYS = [
    'h1',
    'h2',
    'h3',
    'h4',
    'h5',
    'h6',
    'subtitle1',
    'subtitle2',
    'body1',
    'body2',
    'button',
    'caption',
    'overline',
    'inherit',
] as const;

/**
 * Host-theme keys allowed to flow into the collection theme (allowlist).
 *
 * @remarks
 * The vis-2 host theme (gui-components, MUI 9) is a CSS-variables theme: besides
 * `components` (an admin skin with hardcoded surface colors) it carries the whole
 * cssVars machinery — `vars` (a `var(--mui-p…)` mirror of the palette),
 * `colorSchemes`, `getCssVar`, `generateStyleSheets`, … . MUI components resolve
 * colors via `(theme.vars || theme).palette.…`, so a leaked `vars` mirror makes
 * every Paper/Card surface read the HOST's CSS variables instead of the merged
 * palette — the user theme then recolors accents/text but never the surfaces.
 * Only plain-theme DNA passes this allowlist; everything else (skin, cssVars
 * machinery, functions) is dropped and MUI 6 regenerates it from the merge.
 */
const HOST_THEME_ALLOWLIST = [
    'breakpoints',
    'direction',
    'palette',
    'shape',
    'shadows',
    'transitions',
    'typography',
    'zIndex',
] as const;

/** Palette keys regenerated by MUI's `createPalette` (host closures must not survive). */
const PALETTE_FUNCTION_KEYS = ['getContrastText', 'augmentColor'] as const;

/**
 * Reduces the host theme to the DNA the collection may inherit (allowlist).
 *
 * @remarks
 * Two leak classes are defended against (see {@link HOST_THEME_ALLOWLIST}):
 * 1. cssVars machinery (`vars`, `colorSchemes`, …): a leaked `vars` mirror
 *    overrides the merged palette inside every MUI component
 *    (`(theme.vars || theme).palette`), pinning surfaces to the host colors.
 * 2. Component skin (`components`): the modern admin themes hardcode surface
 *    colors (`MuiPaper/MuiCard/… root.backgroundColor`), which as styleOverrides
 *    outrank the palette-driven base styles of the same components.
 * Typography additionally drops the host's pre-generated variant objects and
 * `pxToRem` (see below), palette drops its function closures so `createPalette`
 * regenerates them against the merged values.
 *
 * Exported for the boundary regression test (repo idiom: pure seams are tested
 * directly, cf. useFloatingPanel).
 */
export function sanitizeHostTheme(host: Theme): ThemeOptions {
    const sanitized: Record<string, unknown> = {};
    for (const key of HOST_THEME_ALLOWLIST) {
        const value = (host as unknown as Record<string, unknown>)[key];
        if (value !== undefined) {
            sanitized[key] = value;
        }
    }
    // Typography: strip pre-generated variants so createTypography regenerates
    // them from the merged base values (mui/material-ui#35939, #37043); drop
    // pxToRem, whose host coef would pin variants to the host base size.
    const { typography } = host;
    if (typography) {
        const stripped: Record<string, unknown> = { ...typography };
        for (const key of TYPOGRAPHY_VARIANT_KEYS) {
            delete stripped[key];
        }
        delete stripped.pxToRem;
        sanitized.typography = stripped;
    }
    // Palette: drop function closures (getContrastText/augmentColor bake the
    // host palette) — createPalette regenerates both from the merged palette.
    const { palette } = host;
    if (palette) {
        const cleaned: Record<string, unknown> = { ...palette };
        for (const key of PALETTE_FUNCTION_KEYS) {
            delete cleaned[key];
        }
        sanitized.palette = cleaned;
    }
    return sanitized as ThemeOptions;
}

/**
 * Builds the effective collection theme from the host theme, optional caller
 * overrides, and the user-supplied theme state.
 *
 * Merge precedence (later wins): `hostTheme` → `overrides` → user `parsedTheme`.
 * The user theme therefore takes priority, matching the previous inline logic in
 * `CollectionProvider`.
 *
 * @param socket - ioBroker socket (`Connection`) for reading/subscribing the theme state.
 * @param hostTheme - The vis-2 host theme to merge onto.
 * @param overrides - Optional collection-specific overrides (e.g. typography). Editors omit this.
 * @returns The merged MUI theme.
 * @example
 * ```tsx
 * // Runtime provider (with widget-style overrides):
 * const theme = useCollectionTheme(socket, context.theme, overrides);
 * // Editor surface (host + user theme only):
 * const theme = useCollectionTheme(props.context.socket, props.context.theme) as VisTheme;
 * ```
 */
export function useCollectionTheme(socket: Connection, hostTheme: Theme, overrides?: ThemeOptions): Theme {
    // User-supplied MUI theme JSON, read from the shared ioBroker state.
    const [themeJson, setThemeJson] = useState('');

    useEffect(() => {
        let active = true;
        const handler = (_id: string, state: ioBroker.State | null | undefined): void => {
            if (active) {
                setThemeJson(typeof state?.val === 'string' ? state.val : '');
            }
        };
        socket
            .getState(THEME_STATE_ID)
            .then((state: ioBroker.State | null | undefined) => {
                if (active) {
                    setThemeJson(typeof state?.val === 'string' ? state.val : '');
                }
            })
            .catch((e: unknown) => console.error(`Cannot read theme state ${THEME_STATE_ID}: ${e}`));
        socket
            .subscribeState(THEME_STATE_ID, handler)
            .catch((e: unknown) => console.error(`Cannot subscribe theme state ${THEME_STATE_ID}: ${e}`));
        return () => {
            active = false;
            // Connection.unsubscribeState returns void, not a Promise, so it
            // cannot be chained with .catch(). Wrap it to avoid an uncaught error
            // during effect cleanup (e.g. React StrictMode double-invoke / unmount).
            try {
                socket.unsubscribeState(THEME_STATE_ID, handler);
            } catch (e) {
                console.error(`Cannot unsubscribe theme state ${THEME_STATE_ID}: ${e}`);
            }
        };
    }, [socket]);

    // Parsed, validated user theme; empty object when unset or invalid.
    // JSON is only touched here at the ioBroker state boundary — the validator
    // itself works on the plain object. A corrupt/invalid state must never crash
    // rendering, hence the try/catch and `{}` fallback.
    const parsedTheme = useMemo(() => {
        if (!themeJson) {
            return {};
        }
        try {
            const result = validateThemeOptions(JSON.parse(themeJson));
            return result.isValid ? (result.theme ?? {}) : {};
        } catch {
            return {};
        }
    }, [themeJson]);

    // In-progress draft from the studio panel (null when the panel is closed).
    // The draft wins over the persisted theme so canvas widgets preview edits
    // live; when null, widgets fall back to the persisted theme.
    const draft = useDraftTheme();
    const userTheme = draft ?? parsedTheme;

    // Inject @font-face rules for Google Fonts stored in the effective theme
    // (the draft while editing, the persisted theme otherwise). Idempotent.
    useEffect(() => {
        injectGoogleFontFaces(userTheme.googleFonts);
    }, [userTheme.googleFonts]);

    // Ensure the bundled @fontsource faces the effective theme references are
    // injected (ADR-0020: lazy — only the configured family loads, as async
    // chunks; the other nine families never ship over the wire). font-display:
    // swap covers the brief async window.
    const fontFamily = getNestedValue<string>(userTheme, 'typography.fontFamily');
    useEffect(() => {
        void ensureBundledFontFaces(bundledFamiliesOf(fontFamily));
    }, [fontFamily]);

    // Seamless save-handoff: once the persisted state echoes the draft the panel
    // just saved, retire the draft so widgets read the persisted value. They are
    // equal at that instant, so there is no visible change (no flicker). The
    // `changed` guard avoids clearing the draft the moment the panel opens and
    // first pushes a draft that happens to equal the persisted theme.
    // ADR-0020: the draft string comes from the store (stringified ONCE per flush,
    // shared by all widgets); the persisted side is memoized per widget and only
    // recomputed when the state actually echoes a new value.
    const parsedThemeString = useMemo(() => JSON.stringify(parsedTheme), [parsedTheme]);
    const prevParsedTheme = useRef(parsedTheme);
    useEffect(() => {
        const changed = prevParsedTheme.current !== parsedTheme;
        prevParsedTheme.current = parsedTheme;
        if (draft && changed && getDraftThemeString() === parsedThemeString) {
            clearDraftTheme();
        }
    }, [draft, parsedTheme, parsedThemeString]);

    return useMemo(() => {
        // Reduce the host to inheritable DNA (no cssVars machinery, no
        // component skin — see sanitizeHostTheme). Chain:
        // hostSanitized → overrides → userTheme (draft ?? parsed, with derived
        // secondary + text follows primary); user wins.
        const hostSanitized = sanitizeHostTheme(hostTheme);
        // Text follows the effective primary (user override wins, else the host
        // primary), so body text stays consistent with the chosen accent.
        const hostPrimary = getNestedValue<string>(hostSanitized, 'palette.primary.main');
        const userThemeWithDerived = withPrimaryAsText(withDerivedSecondary(userTheme), hostPrimary);
        const merged = deepmerge(deepmerge(hostSanitized, overrides ?? {}), userThemeWithDerived);
        // Per-corner border radius on widget surfaces (MuiPaper/MuiCard). MUI's
        // shape.borderRadius is single-valued, so inject a 4-value CSS string
        // (and a representative single value for non-surface components).
        const corners = getNestedValue<CornerRadii>(merged, 'corners');
        const radiusCss = buildCornerRadiusCss(corners);
        const withCorners = radiusCss
            ? deepmerge(merged, {
                  shape: { borderRadius: corners?.topLeft ?? 4 },
                  components: {
                      MuiPaper: { styleOverrides: { root: { borderRadius: radiusCss } } },
                      MuiCard: { styleOverrides: { root: { borderRadius: radiusCss } } },
                  },
              })
            : merged;
        return createThemeCached(withCorners);
    }, [hostTheme, overrides, userTheme]);
}

export default useCollectionTheme;
