/**
 * The one theme resolution shared by the canvas widgets and the Theme Studio (ADR-0020).
 *
 * @module lib/theme/resolveCollectionTheme
 * @remarks
 * Host theme, optional caller overrides and the user theme resolve to the effective MUI theme
 * here, and only here: {@link module:hooks/useCollectionTheme.useCollectionTheme} calls it for
 * every canvas widget, the studio panel calls it with the chrome theme as host stand-in, so a
 * colour field always shows the colour the widgets render (glossary "Effektive Farbe").
 *
 * Chain (later wins): `sanitizeHostTheme(host)` → `overrides` → user theme (unusable colours
 * dropped, derived secondary, text follows the effective primary) → per-corner radii →
 * collection CSS variables (own prefix, no `color-scheme`) → `createThemeCached`.
 */

import { deepmerge } from '@mui/utils';
import { decomposeColor } from '@mui/material/styles';
import type { Theme, ThemeOptions } from '@mui/material/styles';

import { createThemeCached } from './createThemeCache';
import { withDerivedSecondary, withPrimaryAsText } from './derivePalette';
import type { CornerRadii, UserTheme } from './themeTypes';
import { DEFAULT_CORNER_RADIUS, buildCornerRadiusCss, getNestedValue, isPlainObject } from './themeUtils';
import { isValidCssColor } from './validateTheme';

/** Standard MUI typography variant keys that `createTypography` regenerates. */
const TYPOGRAPHY_VARIANT_KEYS = [
    'h1',
    'h2',
    'h3',
    'h4',
    'h5',
    'h6',
    'subtitle1',
    'subtitle2',
    'body1',
    'body2',
    'button',
    'caption',
    'overline',
    'inherit',
] as const;

/**
 * Host-theme keys allowed to flow into the collection theme (allowlist).
 *
 * @remarks
 * The vis-2 host theme (gui-components, MUI 9) is a CSS-variables theme: besides
 * `components` (an admin skin with hardcoded surface colors) it carries the whole
 * cssVars machinery — `vars` (a `var(--mui-p…)` mirror of the palette),
 * `colorSchemes`, `getCssVar`, `generateStyleSheets`, … . MUI components resolve
 * colors via `(theme.vars || theme).palette.…`, so a leaked `vars` mirror makes
 * every Paper/Card surface read the HOST's CSS variables instead of the merged
 * palette — the user theme then recolors accents/text but never the surfaces.
 * Only plain-theme DNA passes this allowlist; everything else (skin, cssVars
 * machinery, functions) is dropped and the host's MUI 9 (ADR-0112) regenerates
 * it from the merge.
 */
const HOST_THEME_ALLOWLIST = [
    'breakpoints',
    'direction',
    'palette',
    'shape',
    'shadows',
    'transitions',
    'typography',
    'zIndex',
] as const;

/** Palette keys regenerated by MUI's `createPalette` (host closures must not survive). */
const PALETTE_FUNCTION_KEYS = ['getContrastText', 'augmentColor'] as const;

/**
 * The prefix of the collection's CSS variables (`--vis2c-palette-primary-main`, spec B17).
 *
 * @remarks
 * The vis-2 editor defines `--mui-*` on `:root`, and MUI writes a CSS-variables theme to
 * `:root` as well — with MUI's default prefix the user theme overwrote the editor's own
 * variables (verified in `cssVariablesCollision.test.tsx`).
 */
export const COLLECTION_CSS_VAR_PREFIX = 'vis2c';

/** The CSS-variables prefix the host editor owns (`--mui-*`): the collection never emits it. */
export const HOST_CSS_VAR_PREFIX = 'mui';

/** Palette slots MUI augments: their `main` feeds lighten/darken/getContrastText. */
export const AUGMENTED_SLOTS: ReadonlySet<string> = new Set([
    'primary',
    'secondary',
    'error',
    'warning',
    'info',
    'success',
]);

/**
 * Reduces the host theme to the DNA the collection may inherit (allowlist, ADR-0078).
 *
 * @remarks
 * Two leak classes are defended against (see {@link HOST_THEME_ALLOWLIST}):
 * 1. cssVars machinery (`vars`, `colorSchemes`, …): a leaked `vars` mirror
 *    overrides the merged palette inside every MUI component
 *    (`(theme.vars || theme).palette`), pinning surfaces to the host colors.
 * 2. Component skin (`components`): the modern admin themes hardcode surface
 *    colors (`MuiPaper/MuiCard/… root.backgroundColor`), which as styleOverrides
 *    outrank the palette-driven base styles of the same components.
 * Typography additionally drops the host's pre-generated variant objects and
 * `pxToRem` (see below), palette drops its function closures so `createPalette`
 * regenerates them against the merged values.
 */
export function sanitizeHostTheme(host: Theme): ThemeOptions {
    const sanitized: Record<string, unknown> = {};
    for (const key of HOST_THEME_ALLOWLIST) {
        const value = (host as unknown as Record<string, unknown>)[key];
        if (value !== undefined) {
            sanitized[key] = value;
        }
    }
    // Typography: strip pre-generated variants so createTypography regenerates
    // them from the merged base values (mui/material-ui#35939, #37043); drop
    // pxToRem, whose host coef would pin variants to the host base size.
    const { typography } = host;
    if (typography) {
        const stripped: Record<string, unknown> = { ...typography };
        for (const key of TYPOGRAPHY_VARIANT_KEYS) {
            delete stripped[key];
        }
        delete stripped.pxToRem;
        sanitized.typography = stripped;
    }
    // Palette: drop function closures (getContrastText/augmentColor bake the
    // host palette) — createPalette regenerates both from the merged palette.
    const { palette } = host;
    if (palette) {
        const cleaned: Record<string, unknown> = { ...palette };
        for (const key of PALETTE_FUNCTION_KEYS) {
            delete cleaned[key];
        }
        sanitized.palette = cleaned;
    }
    return sanitized;
}

/**
 * Whether MUI's colour maths (lighten/darken/contrast) can parse the value — an augmented slot's
 * `main` that fails this is dropped by the resolution (the studio validation reports it).
 */
export function isComputableColor(value: string): boolean {
    try {
        decomposeColor(value);
        return true;
    } catch {
        return false;
    }
}

/** The `cssVariables.cssVarPrefix` a theme sets, if it is a string. */
export function ownCssVarPrefix(theme: object): string | undefined {
    const cssVariables: unknown = (theme as Record<string, unknown>).cssVariables;
    const prefix = isPlainObject(cssVariables) ? cssVariables.cssVarPrefix : undefined;
    return typeof prefix === 'string' ? prefix : undefined;
}

/**
 * Gives enabled CSS variables the collection's own namespace.
 *
 * @remarks
 * The prefix defaults to {@link COLLECTION_CSS_VAR_PREFIX} (also for `cssVariables: true`, an
 * empty and a reserved prefix), and `color-scheme` stays off unless the theme asks for it: the
 * stylesheet targets `:root`, where it would override the editor's own `color-scheme` (native
 * scrollbars and form controls of the whole editor). Off (`false`/unset) stays untouched.
 */
function withCollectionCssVariables(options: ThemeOptions): ThemeOptions {
    const cssVariables: unknown = (options as Record<string, unknown>).cssVariables;
    if (cssVariables !== true && !isPlainObject(cssVariables)) {
        return options;
    }
    const own = isPlainObject(cssVariables) ? cssVariables : {};
    const prefix = ownCssVarPrefix(options);
    const cssVarPrefix =
        prefix !== undefined && prefix !== '' && prefix !== HOST_CSS_VAR_PREFIX ? prefix : COLLECTION_CSS_VAR_PREFIX;
    return {
        ...options,
        cssVariables: { disableCssColorScheme: true, ...own, cssVarPrefix },
    };
}

/**
 * Copies a palette (sub)tree without the colour leaves the widgets cannot use.
 *
 * @remarks
 * Every string leaf of the palette except `mode` is a colour (theme schema). A leaf the browser
 * rejects is dropped; an augmented slot's `main` must also be computable by MUI, which otherwise
 * throws inside `createTheme` ("MUI: Unsupported color") — named colours and `transparent` pass
 * the browser but not MUI. Returns the input itself when nothing was dropped.
 * @param node - The palette (sub)tree.
 * @param level - Where `node` sits: the palette root (its `mode` is no colour), an augmented
 *   slot (its `main` must be computable) or any other node.
 */
function withoutUnusableLeaves(
    node: Record<string, unknown>,
    level: 'palette' | 'augmented-slot' | 'other',
): Record<string, unknown> {
    let result: Record<string, unknown> | null = null;
    for (const [key, value] of Object.entries(node)) {
        let next: unknown = value;
        if (isPlainObject(value)) {
            next = withoutUnusableLeaves(
                value,
                level === 'palette' && AUGMENTED_SLOTS.has(key) ? 'augmented-slot' : 'other',
            );
        } else if (typeof value === 'string' && !(level === 'palette' && key === 'mode')) {
            const usable =
                isValidCssColor(value) && (level !== 'augmented-slot' || key !== 'main' || isComputableColor(value));
            next = usable ? value : undefined;
        }
        if (next !== value) {
            result ??= { ...node };
            if (next === undefined) {
                delete result[key];
            } else {
                result[key] = next;
            }
        }
    }
    return result ?? node;
}

/**
 * Drops the user theme's unusable colours, so each such field inherits like an unset one.
 *
 * @remarks
 * The studio draft reaches the resolution unvalidated (the field validation reports the
 * problem, ADR-0020); an invalid colour must never crash a canvas widget or the panel.
 */
function withoutUnusableColors(theme: UserTheme): UserTheme {
    const { palette } = theme;
    if (!isPlainObject(palette)) {
        return theme;
    }
    const cleaned = withoutUnusableLeaves(palette, 'palette');
    return cleaned === palette ? theme : { ...theme, palette: cleaned };
}

/**
 * Resolves the effective collection theme.
 *
 * @param hostTheme - The host theme (vis-2 context theme; the studio passes the chrome theme).
 * @param overrides - Collection-specific overrides between host and user theme (e.g. typography).
 * @param userTheme - The user theme (persisted state or the studio draft).
 * @returns The created (shared, cached) MUI theme.
 */
export function resolveCollectionTheme(
    hostTheme: Theme,
    overrides: ThemeOptions | undefined,
    userTheme: UserTheme,
): Theme {
    // Reduce the host to inheritable DNA (no cssVars machinery, no component skin).
    const hostSanitized = sanitizeHostTheme(hostTheme);
    // Text follows the effective primary (user override wins, else the host primary), so body
    // text stays consistent with the chosen accent.
    const hostPrimary = getNestedValue<string>(hostSanitized, 'palette.primary.main');
    const userThemeWithDerived = withPrimaryAsText(withDerivedSecondary(withoutUnusableColors(userTheme)), hostPrimary);
    const merged = deepmerge(deepmerge(hostSanitized, overrides ?? {}), userThemeWithDerived);
    // Per-corner border radius on widget surfaces (MuiPaper/MuiCard). MUI's
    // shape.borderRadius is single-valued, so inject a 4-value CSS string
    // (and a representative single value for non-surface components).
    const corners = getNestedValue<CornerRadii>(merged, 'corners');
    const radiusCss = buildCornerRadiusCss(corners);
    const withCorners = radiusCss
        ? deepmerge(merged, {
              shape: { borderRadius: corners?.topLeft ?? DEFAULT_CORNER_RADIUS },
              components: {
                  MuiPaper: { styleOverrides: { root: { borderRadius: radiusCss } } },
                  MuiCard: { styleOverrides: { root: { borderRadius: radiusCss } } },
              },
          })
        : merged;
    return createThemeCached(withCollectionCssVariables(withCorners));
}
